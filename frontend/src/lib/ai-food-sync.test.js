// @vitest-environment happy-dom
import { describe, expect, it } from 'vitest'
import {
  buildAiFoodLink,
  buildAiSetupPrompt,
  inferCategoryClient,
  parseAiChatReplyText,
  parseAiFoodLink,
} from './ai-food-sync.js'

describe('Universal AI food sync helpers', () => {
  it('encodes and decodes compact base64url deep links with macros and provider attribution', () => {
    const link = buildAiFoodLink('https://aetherix.app', {
      name: 'Grilled Salmon & Rice Bowl',
      kcalPerUnit: 580,
      qty: 1,
      unitLabel: 'bowl',
      category: 'Lunch',
      proteinG: 42,
      carbsG: 52,
      fatG: 20,
      fiberG: 4,
      aiProvider: 'gemini',
    })
    expect(link).toContain('/#/food?ai_log=')

    const parsed = parseAiFoodLink(link)
    expect(parsed).toBeTruthy()
    expect(parsed.meal.name).toBe('Grilled Salmon & Rice Bowl')
    expect(parsed.meal.kcal).toBe(580)
    expect(parsed.meal.category).toBe('Lunch')
    expect(parsed.meal.nutrientSource).toBe('ai:gemini')
    expect(parsed.meal.nutrients.proteinG).toBe(42)
    expect(parsed.meal.nutrients.carbsG).toBe(52)
    expect(parsed.meal.nutrients.fatG).toBe(20)
  })

  it('parses flat query-param deep links generated by ChatGPT, Gemini, Grok, or Claude', () => {
    const url = 'https://aetherix.app/#/food?name=Masala%20Dosa&kcal=320&p=7&c=46&f=11&cat=Breakfast&qty=2&unit=piece&ai=chatgpt'
    const parsed = parseAiFoodLink(url)
    expect(parsed).toBeTruthy()
    expect(parsed.meal.name).toBe('Masala Dosa')
    expect(parsed.meal.qty).toBe(2)
    expect(parsed.meal.kcalPerUnit).toBe(160)
    expect(parsed.meal.kcal).toBe(320)
    expect(parsed.meal.category).toBe('Breakfast')
    expect(parsed.meal.nutrientSource).toBe('ai:chatgpt')
    expect(parsed.meal.nutrients.proteinG).toBe(3.5)
  })

  it('parses pasted JSON blocks, markdown tables, and natural prose replies', () => {
    const jsonReply = [
      'Here is your meal breakdown from Claude:',
      '```json',
      '{ "name": "Chicken Biryani", "kcal": 540, "proteinG": 28, "carbsG": 58, "fatG": 21, "category": "Lunch", "sourceAi": "claude" }',
      '```',
    ].join('\n')
    const p1 = parseAiChatReplyText(jsonReply)
    expect(p1.name).toBe('Chicken Biryani')
    expect(p1.kcal).toBe(540)
    expect(p1.category).toBe('Lunch')
    expect(p1.nutrientSource).toBe('ai:claude')
    expect(p1.nutrients.proteinG).toBe(28)

    const proseReply = [
      '**Chicken Tikka Wrap**',
      '- Calories: ~465 kcal',
      '- Protein: 36g',
      '- Carbs: 42g',
      '- Fat: 16g',
      '- Fiber: 5g',
      'Logged via Grok',
    ].join('\n')
    const p2 = parseAiChatReplyText(proseReply)
    expect(p2.name).toBe('Chicken Tikka Wrap')
    expect(p2.kcal).toBe(465)
    expect(p2.nutrientSource).toBe('ai:grok')
    expect(p2.nutrients.proteinG).toBe(36)
    expect(p2.nutrients.carbsG).toBe(42)
    expect(p2.nutrients.fatG).toBe(16)
    expect(p2.nutrients.fiberG).toBe(5)
  })

  it('infers categories cleanly and builds platform-specific setup prompts', () => {
    expect(inferCategoryClient('Whey Protein Shake', '')).toBe('Protein')
    expect(inferCategoryClient('Masala Chai', '')).toBe('Drinks')
    expect(inferCategoryClient('Plain Idli', '')).toBe('Breakfast')

    const gemPrompt = buildAiSetupPrompt('gemini', 'https://aetherix.app')
    expect(gemPrompt).toContain('https://aetherix.app/#/food?')
    expect(gemPrompt).toContain('ai=gemini')

    const gptActionPrompt = buildAiSetupPrompt('chatgpt', 'https://aetherix.app', { aiKey: 'ax_••••1234' })
    expect(gptActionPrompt).toContain('logFoodMeal')
    expect(gptActionPrompt).toContain('ai=chatgpt')
  })
})
